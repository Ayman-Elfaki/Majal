using Majal.Common.Abstractions;
using static Majal.Common.Abstractions.Constants;

namespace Majal.Generators.Entities;

public abstract class EntityTemplateBase : BaseTemplate
{
    protected void WriteForeignKeys(IEnumerable<EntityGenerator.ForeignKeyData> foreignKeys, EquatableList<string> properties)
    {
        foreach (var fk in foreignKeys)
        {
            if (properties.Contains(fk.Name)) continue;
            WriteLine("");
            WriteLine("/// <summary>");
            WriteLine($"/// Gets or sets the foreign key for <see cref=\"{fk.NavigationPropertyName}\"/>.");
            WriteLine("/// </summary>");
            var initializer = (!fk.IsNullable && !fk.IsValueType) ? " = default!;" : string.Empty;
            WriteLine($"public {fk.Type} {fk.Name} {{ get; set; }}{initializer}");
        }
    }
}

/// <summary>
/// Generates a partial for a class derived from an entity, containing only foreign keys.
/// </summary>
public class DerivedEntityTemplate(EntityGenerator.DerivedEntityData data) : EntityTemplateBase
{
    public override string TransformText()
    {
        Clear();
        WriteLine("// <auto-generated />");
        WriteLine("");
        WriteLine("#nullable enable");
        WriteLine("");
        WriteLine(data.Namespace);
        WriteLine("");
        WriteLine("/// <summary>");
        WriteLine($"/// Provides foreign keys for <see cref=\"{data.RawTypeName}\"/>.");
        WriteLine("/// </summary>");
        WriteLine($"public partial class {data.TypeName}");
        WriteLine("{");
        PushIndent();
        WriteForeignKeys(data.ForeignKeys, data.Properties);
        PopIndent();
        WriteLine("}");
        return ToString();
    }
}

public class EntityTemplate(EntityGenerator.EntityData data) : EntityTemplateBase
{
    public override string TransformText()
    {
        Clear();
        WriteLine("// <auto-generated />");
        WriteLine("");
        WriteLine("#nullable enable");
        WriteLine("");
        WriteLine(data.Namespace);
        WriteLine("");

        string[] interfaces =
        [
            $"{MajalNamespace}.IEntity<{data.IdType}>",
            $"{SystemNamespace}.IComparable",
            $"{SystemNamespace}.IComparable<{data.TypeName}>"
        ];

        WriteLine("/// <summary>");
        WriteLine($"/// Provides entity infrastructure for <see cref=\"{data.RawTypeName}\"/>.");
        WriteLine("/// </summary>");
        WriteLine($"public partial class {data.TypeName} : {string.Join(", ", interfaces)}");
        WriteLine("{");
        PushIndent();

        if (!data.HasConstructor)
        {
            WriteLine("/// <summary>");
            WriteLine($"/// Initializes a new instance of <see cref=\"{data.RawTypeName}\"/>.");
            WriteLine("/// </summary>");
            WriteLine($"protected {data.RawTypeName}()");
            WriteLine("{");
            WriteLine("}");
        }

        if (!data.Properties.Contains("Id"))
        {
            WriteLine("/// <inheritdoc />");
            WriteLine($"public {data.IdType} Id {{ get; set; }} = default!;");
        }

        WriteForeignKeys(data.ForeignKeys, data.Properties);

        WriteLine("");
        WriteLine("/// <inheritdoc />");
        WriteLine($"public override {BoolType} Equals({ObjectType}? obj)");
        WriteLine("{");
        PushIndent();
        WriteLine($"if (obj is not {data.TypeName} other) return false;");
        WriteLine("if (ReferenceEquals(this, other)) return true;");
        WriteLine("if (IsTransient() || other.IsTransient()) return false;");
        WriteLine("return Id.Equals(other.Id);");
        PopIndent();
        WriteLine("}");
        WriteLine("");
        WriteLine("/// <summary>Determines whether this entity is transient (not yet persisted to the data store).</summary>");
        WriteLine($"private {BoolType} IsTransient()");
        WriteLine("{");
        PushIndent();
        WriteLine($"return Id.Equals(default({data.IdType}));");
        PopIndent();
        WriteLine("}");
        WriteLine("");
        WriteLine("/// <inheritdoc />");
        WriteLine($"public static {BoolType} operator ==({data.TypeName}? a, {data.TypeName}? b)");
        WriteLine("{");
        PushIndent();
        WriteLine("if (a is null && b is null) return true;");
        WriteLine("if (a is null || b is null) return false;");
        WriteLine("return a.Equals(b);");
        PopIndent();
        WriteLine("}");
        WriteLine("");
        WriteLine("/// <inheritdoc />");
        WriteLine($"public static {BoolType} operator !=({data.TypeName}? a, {data.TypeName}? b)");
        WriteLine("{");
        PushIndent();
        WriteLine("return !(a == b);");
        PopIndent();
        WriteLine("}");
        WriteLine("");
        WriteLine("/// <inheritdoc />");
        WriteLine($"public override {IntType} GetHashCode()");
        WriteLine("{");
        PushIndent();
        WriteLine("return (GetType().ToString() + Id).GetHashCode();");
        PopIndent();
        WriteLine("}");
        WriteLine("");
        WriteLine("/// <inheritdoc />");
        WriteLine($"public {IntType} CompareTo({data.TypeName}? other)");
        WriteLine("{");
        PushIndent();
        WriteLine("if (other is null) return 1;");
        WriteLine("if (ReferenceEquals(this, other)) return 0;");
        WriteLine("return Id.CompareTo(other.Id);");
        PopIndent();
        WriteLine("}");
        WriteLine("");
        WriteLine("/// <inheritdoc />");
        WriteLine($"public {IntType} CompareTo({ObjectType}? other)");
        WriteLine("{");
        PushIndent();
        WriteLine($"return CompareTo(other as {data.TypeName});");
        PopIndent();
        WriteLine("}");

        PopIndent();
        WriteLine("}");

        return ToString();
    }
}